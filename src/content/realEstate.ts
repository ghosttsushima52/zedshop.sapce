export function getPropertyBySlug(slug: string): PropertyListing | undefined {
  return propertyListings.find((item) => item.slug === slug);
}

export function getPropertiesByCategory(category: string): PropertyListing[] {
  return propertyListings.filter((item) => item.category === category);
}

export function getPropertiesByCity(city: string): PropertyListing[] {
  return propertyListings.filter((item) => item.location.city.toLowerCase().includes(city.toLowerCase()));
}

export function getPropertiesByCountry(country: string): PropertyListing[] {
  return propertyListings.filter((item) => item.location.country.toLowerCase() === country.toLowerCase());
}

export function getFeaturedProperties(): PropertyListing[] {
  return propertyListings.filter((item) => item.featured);
}
