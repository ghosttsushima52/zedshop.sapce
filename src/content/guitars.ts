export function getGuitarBySlug(slug: string): GuitarProduct | undefined {
  return guitars.find((g) => g.slug === slug);
}

export function getGuitarsByCategory(category: GuitarCategory): GuitarProduct[] {
  return guitars.filter((g) => g.category === category);
}

export function getLeftHandedGuitars(): GuitarProduct[] {
  return guitars.filter((g) => g.handedness === 'Sol El');
}

